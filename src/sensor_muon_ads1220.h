//
// The chip converts continuously from its own oscillator (+/-2%). The mcu
// reads RDATA, which returns the most recent conversion, at a little over
// twice the nominal conversion rate. A new conversion is therefore always
// seen within one read interval of completing, and none can complete
// unseen unless a read is late.
//
// A changed value marks a new conversion. An unchanged value is either the
// same conversion read twice, or a new conversion that happened to produce
// the same 24-bit code. At gain 64 and 2000SPS the noise is ~180 counts RMS
// and consecutive identical codes happen about three times a second, so
// unchanged values cannot simply be dropped. Timing separates the two: once
// a read is later than the longest possible conversion period after the
// previous conversion was seen, a conversion must have completed, and an
// unchanged value is then a real repeat.
//
// The stream also keeps one sample slot per nominal conversion period
// across the gaps where the chip is measuring temperature, so the host's
// fixed-frequency clock tracking (bulk_sensor.FixedFreqReader) still holds.
// Slots with no measurement carry MADS_FILLER, which the host discards.
//
// Everything here is plain integer arithmetic with no division, so it can
// be compiled into host-side tests as well as the firmware.

#ifndef __SENSOR_MUON_ADS1220_H
#define __SENSOR_MUON_ADS1220_H

#include <stdint.h>

// Sample value carried in a slot that holds no measurement
#define MADS_FILLER ((int32_t)0x80000000)
// Cap on slots generated by a single read, so one wild read cannot flood
// the bulk stream
#define MADS_MAX_SLOTS 32

struct mads_sampler {
    // Nominal, shortest and longest conversion period, in mcu ticks
    uint32_t conv_ticks, conv_min_ticks, conv_max_ticks;
    // Time of the previous RDATA read, and of the read that last emitted
    uint32_t last_read_time, last_emit_time;
    // Estimated completion time of the last conversion given a slot
    uint32_t last_conv_time;
    // Expected completion of the first conversion after a restart
    uint32_t first_conv_time;
    // A conversion must have completed by this time
    uint32_t dup_deadline;
    int32_t last_raw;
    // Repeats emitted since the value last changed
    uint16_t dup_run;
    uint8_t have_conv, in_segment;
    // Statistics, reported to the host
    uint32_t n_new, n_dup, n_hold, n_filler, n_late;
};

// What to put in the stream for one read: 'fillers' empty slots, then
// 'holds' copies of the previous value (conversions that a late read
// missed), then the value itself if 'emit' is set. 'lost' counts the
// conversions this read knows it missed (held or not).
struct mads_result {
    uint8_t fillers, holds, emit, late, lost;
    int32_t hold_value, value;
};

static inline int
mads_before(uint32_t a, uint32_t b)
{
    return (int32_t)(a - b) < 0;
}

// Whole periods in delta, rounded down, without a divide
static inline uint32_t
mads_floor_periods(int32_t delta, uint32_t period, uint32_t limit)
{
    uint32_t n = 0;
    while (delta >= (int32_t)period && n < limit) {
        delta -= period;
        n++;
    }
    return n;
}

// Round (delta / conv) to the nearest integer for small positive ratios,
// without a divide. Returns 0 for negative or tiny deltas.
static inline uint32_t
mads_periods(int32_t delta, uint32_t conv, uint32_t limit)
{
    if (delta <= 0)
        return 0;
    uint32_t n = 0, half = conv >> 1, d = delta;
    while (d >= conv - half && n < limit) {
        n++;
        if (d < conv)
            break;
        d -= conv;
    }
    return n;
}

static inline void
mads_sampler_init(struct mads_sampler *s, uint32_t conv_ticks
                  , uint32_t conv_min_ticks, uint32_t conv_max_ticks)
{
    s->conv_ticks = conv_ticks;
    s->conv_min_ticks = conv_min_ticks;
    s->conv_max_ticks = conv_max_ticks;
    s->last_read_time = s->last_emit_time = s->last_conv_time = 0;
    s->first_conv_time = s->dup_deadline = 0;
    s->last_raw = 0;
    s->have_conv = s->in_segment = 0;
    s->dup_run = 0;
    s->n_new = s->n_dup = s->n_hold = s->n_filler = s->n_late = 0;
}

// The load cell configuration was just written (which restarts the
// conversion); its first conversion is expected at first_conv_time.
static inline void
mads_sampler_restart(struct mads_sampler *s, uint32_t first_conv_time)
{
    s->first_conv_time = first_conv_time;
    s->in_segment = 0;
}

// Forget all timing history (stream stopped)
static inline void
mads_sampler_reset(struct mads_sampler *s)
{
    s->have_conv = s->in_segment = 0;
    s->dup_run = 0;
}

// While the chip is measuring something else, the empty slots that have
// certainly passed. Lags one period behind so a slot is never issued for
// time the resumed stream will fill itself.
static inline uint32_t
mads_sampler_gap_fill(struct mads_sampler *s, uint32_t now)
{
    if (!s->have_conv)
        return 0;
    uint32_t n = 0;
    while (n < MADS_MAX_SLOTS
           && !mads_before(now, s->last_conv_time + 2 * s->conv_ticks)) {
        s->last_conv_time += s->conv_ticks;
        n++;
    }
    s->n_filler += n;
    return n;
}

// Process one RDATA result 'raw' read at time 'now'
static inline void
mads_sampler_read(struct mads_sampler *s, uint32_t now, int32_t raw
                  , struct mads_result *r)
{
    r->fillers = r->holds = r->emit = r->late = r->lost = 0;
    r->hold_value = s->last_raw;
    r->value = raw;
    if (!s->in_segment) {
        // First read after a restart. It is timed to land after the first
        // conversion of the new configuration, so it is a new conversion
        // whatever its value. A read late by a conversion period or more
        // got a later one; the earlier ones are lost and get empty slots.
        uint32_t c = s->first_conv_time, skipped = 0;
        int32_t d = (int32_t)(now - c);
        while (d >= (int32_t)s->conv_min_ticks
               && skipped < MADS_MAX_SLOTS) {
            d -= s->conv_ticks;
            c += s->conv_ticks;
            skipped++;
        }
        if (skipped) {
            r->late = 1;
            r->lost = skipped;
            s->n_late++;
        }
        if (s->have_conv) {
            uint32_t n = mads_periods((int32_t)(c - s->last_conv_time)
                                      , s->conv_ticks, MADS_MAX_SLOTS + 1);
            r->fillers = n > 1 ? n - 1 : 0;
            s->n_filler += r->fillers;
        }
        r->emit = 1;
        s->n_new++;
        s->last_conv_time = c;
        s->have_conv = s->in_segment = 1;
        s->dup_deadline = now + s->conv_max_ticks;
        s->dup_run = 0;
        s->last_raw = raw;
        s->last_read_time = s->last_emit_time = now;
        return;
    }
    uint32_t gap = now - s->last_read_time;
    if (gap > s->conv_min_ticks) {
        // Reads were further apart than a conversion: one may be lost
        r->late = 1;
        s->n_late++;
    }
    if (raw != s->last_raw) {
        // A new conversion completed somewhere in (last_read_time, now],
        // and no earlier than now - conv_max_ticks (it is the latest). The
        // previous one reported completed no later than last_emit_time, so
        // at least this many conversions came between them unseen. Only
        // those certain losses get held copies, so a hold never invents a
        // conversion; any others are covered by the 'late' flag.
        uint32_t c = now - (gap >> 1);
        uint32_t earliest = s->last_read_time;
        if (mads_before(earliest, now - s->conv_max_ticks))
            earliest = now - s->conv_max_ticks;
        uint32_t n = mads_floor_periods(
            (int32_t)(earliest - s->last_emit_time), s->conv_max_ticks
            , MADS_MAX_SLOTS);
        if (n) {
            r->holds = r->lost = n;
            s->n_hold += n;
        }
        r->emit = 1;
        s->n_new++;
        s->last_conv_time = c;
        s->dup_deadline = now + s->conv_max_ticks;
        s->dup_run = 0;
    } else if (!mads_before(now, s->dup_deadline)) {
        // A conversion must have completed since the value last changed,
        // and it produced the same code
        r->emit = 1;
        s->n_dup++;
        s->last_conv_time += s->conv_ticks;
        s->dup_deadline += s->conv_max_ticks;
        if (s->dup_run < 0xffff)
            s->dup_run++;
    }
    if (r->emit)
        s->last_emit_time = now;
    s->last_raw = raw;
    s->last_read_time = now;
}

#endif // sensor_muon_ads1220.h
